local function AutoAssignTBCWoWSimProfileIfMissing()
  if not MerfinPlus.db or not MerfinPlus.db.global then
    return
  end

  local wowSims = MerfinPlus.db.global.wowSims
  wowSims.profiles = wowSims.profiles or {}
  wowSims.assigned = wowSims.assigned or {}

  local profiles = wowSims.profiles
  local assigned = wowSims.assigned

  local name, realm = UnitName("player")
  if not name then
    return
  end

  realm = realm or GetNormalizedRealmName() or "UNKNOWN"
  local charKey = name .. "-" .. realm
  assigned[charKey] = assigned[charKey] or {}

  local class = select(2, UnitClass("player"))
  if not class then
    return
  end

  local bestTab, bestPoints = nil, -1
  for tab = 1, GetNumTalentTabs() do
    local points = select(5, GetTalentTabInfo(tab))
    if points and points > bestPoints then
      bestPoints = points
      bestTab = tab
    end
  end

  if not bestTab then
    return
  end

  local specIDByClassAndTab = {
    WARRIOR = { [1] = 161, [2] = 164, [3] = 163 },
    PALADIN = { [1] = 382, [2] = 383, [3] = 381 },
    HUNTER = { [1] = 361, [2] = 363, [3] = 362 },
    ROGUE = { [1] = 182, [2] = 181, [3] = 183 },
    PRIEST = { [1] = 201, [2] = 202, [3] = 203 },
    SHAMAN = { [1] = 261, [2] = 263, [3] = 262 },
    MAGE = { [1] = 81, [2] = 41, [3] = 61 },
    WARLOCK = { [1] = 302, [2] = 303, [3] = 301 },
    DRUID = { [1] = 283, [2] = 281, [3] = 282 },
  }

  local specID = specIDByClassAndTab[class] and specIDByClassAndTab[class][bestTab]
  if not specID or assigned[charKey][specID] then
    return
  end

  for key, profile in pairs(profiles) do
    if
      profile
      and profile.class == class
      and profile.specID == specID
      and key
      and key:match("%-PreRaidBIS$")
      and not key:match("FeralTank")
    then
      assigned[charKey][specID] = key
      if WeakAuras and WeakAuras.ScanEvents then
        WeakAuras.ScanEvents("MERFIN_WOWSIM_CHANGED")
      end
      return
    end
  end
end

function MerfinPlus:RegisterTBCWoWSimAutoAssign()
  if self.tbcWoWSimAutoAssignRegistered or not MerfinPlus.IsTBC() then
    return
  end

  self.tbcWoWSimAutoAssignRegistered = true

  local f = CreateFrame("Frame")
  f:RegisterEvent("PLAYER_ENTERING_WORLD")
  f:SetScript("OnEvent", function()
    C_Timer.After(1, function()
      f:UnregisterEvent("PLAYER_ENTERING_WORLD")
      AutoAssignTBCWoWSimProfileIfMissing()
    end)
  end)
end

function MerfinPlus:ModernizeTBCWoWSimDefaults()
  if not MerfinPlus.IsTBC() then
    return
  end

  if not self.db or not self.db.global then
    return
  end

  local wowSims = self.db.global.wowSims

  wowSims.profiles = wowSims.profiles or {}
  wowSims.assigned = wowSims.assigned or {}

  local installedVersion = tonumber(wowSims.internalVersion) or 0
  if installedVersion >= TBC_WOWSIM_INTERNAL_VERSION then
    self:RegisterTBCWoWSimAutoAssign()
    return
  end

  local function AddProfile(key, data)
    -- Version 3 refreshes only the canonical Phase 3 defaults so incomplete
    -- version 2 profiles are repaired. Older defaults and custom profiles keep
    -- their stored values.
    if installedVersion >= 1 and not key:match("%-Phase3BIS$") then
      return
    end
    data.key = key
    wowSims.profiles[key] = data
  end

  self:InstallTBCWoWSimDefaultProfiles(AddProfile)
  wowSims.internalVersion = TBC_WOWSIM_INTERNAL_VERSION
  self:RegisterTBCWoWSimAutoAssign()
end
